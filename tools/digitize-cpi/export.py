def fill_short(v, maxgap=6):
    v = v.copy(); n = len(v); i = 0
    while i < n:
        if np.isnan(v[i]):
            j = i
            while j < n and np.isnan(v[j]): j += 1
            if 0 < i and j < n and (j - i) <= maxgap:
                v[i:j] = np.interp(np.arange(i, j), [i-1, j], [v[i-1], v[j]])
            i = j
        else: i += 1
    return v

